# Regenerates lib/exnode/chain_params/fixed_seeds.ex from Core's fixed-seed
# lists in the vendored tree (vendor/bitcoin/contrib/seeds/nodes_*.txt), the
# same lists Core's generate-seeds.py turns into src/chainparamsseeds.h.
#
#   mix run --no-start scripts/gen_fixed_seeds.exs
#
# The generated module is checked in, so building exnode does not need the
# vendored tree. Rerun this after updating vendor/bitcoin.

alias Exnode.ChainParams.SeedParser

root = Path.expand("..", __DIR__)
seeds_dir = Path.join(root, "vendor/bitcoin/contrib/seeds")
files = [mainnet: "nodes_main.txt", testnet: "nodes_test.txt", testnet4: "nodes_testnet4.txt", signet: "nodes_signet.txt"]

{:ok, commit} =
  case System.cmd("git", ["-C", Path.join(root, "vendor/bitcoin"), "rev-parse", "HEAD"], stderr_to_stdout: true) do
    {c, 0} -> {:ok, String.trim(c)}
    _ -> {:ok, "unknown"}
  end

entries =
  for {net, file} <- files do
    addrs = seeds_dir |> Path.join(file) |> File.read!() |> SeedParser.parse()
    {net, file, addrs}
  end

body =
  for {net, file, addrs} <- entries do
    rows = Enum.map_join(addrs, ",\n      ", fn a -> "{#{inspect(a.net)}, #{inspect(a.addr, binaries: :as_binaries)}, #{a.port}}" end)

    """
      # #{file}: #{length(addrs)} IPv4/IPv6 seeds
      def get(#{inspect(net)}) do
        [
          #{rows}
        ]
        |> Enum.map(fn {net, addr, port} -> %{net: net, addr: addr, port: port} end)
      end
    """
  end

module = """
# GENERATED by scripts/gen_fixed_seeds.exs from vendor/bitcoin/contrib/seeds
# (Bitcoin Core #{commit}). Do not edit by hand.
defmodule Exnode.ChainParams.FixedSeeds do
  @moduledoc \"\"\"
  Core v32.1 fixed seeds (`vFixedSeeds`, `chainparamsseeds.h`), IPv4 and
  IPv6 entries only (the networks exnode can reach). Used by
  `Exnode.P2P.Connman` when the address book has no entries for a reachable
  network 60 s after start (Core `ThreadOpenConnections`).
  \"\"\"

#{Enum.join(body, "\n")}
  def get(_network), do: []
end
"""

out = Path.join(root, "lib/exnode/chain_params/fixed_seeds.ex")
# Formatted as mix format would, so regenerating gives no diff.
File.write!(out, IO.iodata_to_binary([Code.format_string!(module), "\n"]))
for {net, file, addrs} <- entries, do: IO.puts("#{net} (#{file}): #{length(addrs)} seeds")
IO.puts("wrote #{Path.relative_to(out, root)}")
